-- LACV (Laboratory Analysis & Collection Vault)
-- PostgreSQL 17+
-- Design focus:
--   Sample is the single physical identity and lineage tree.
--   sample -> process events / assays -> derived samples; storage and quantity history per sample.
--   Child samples use normal/default values; parent links track lineage only.
-- This file creates the current schema for a fresh database and stamps it at the
-- current Alembic head. Existing databases are upgraded with Alembic instead.
-- The PostgreSQL Docker image creates/selects POSTGRES_DB before running this file.

CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TABLE batches (
    batch_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_code VARCHAR(50) NOT NULL UNIQUE,
    batch_name VARCHAR(255) NOT NULL,
    description TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE sample_types (
    sample_type_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type_code VARCHAR(100) NOT NULL UNIQUE,
    type_name VARCHAR(150) NOT NULL,
    description TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    sort_order INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE process_types (
    process_type_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type_code VARCHAR(100) NOT NULL UNIQUE,
    type_name VARCHAR(150) NOT NULL,
    description TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    sort_order INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE protocols (
    protocol_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    protocol_code VARCHAR(100) NOT NULL,
    protocol_name VARCHAR(255) NOT NULL,
    protocol_version VARCHAR(100) NOT NULL,
    protocol_type VARCHAR(20) NOT NULL DEFAULT 'general',
    description TEXT,
    document_location VARCHAR(1000),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    effective_date DATE,
    retired_date DATE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_protocol_version UNIQUE (protocol_code, protocol_version),
    CONSTRAINT ck_protocol_type CHECK (protocol_type IN ('process', 'assay', 'general'))
);

CREATE TABLE storage_locations (
    storage_location_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_location_id BIGINT NULL,
    location_code VARCHAR(100) NOT NULL,
    location_type VARCHAR(50) NOT NULL,
    location_name VARCHAR(255) NULL,
    description TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_storage_parent FOREIGN KEY (parent_location_id) REFERENCES storage_locations(storage_location_id) ON DELETE SET NULL,
    CONSTRAINT uq_storage_location UNIQUE (parent_location_id, location_code)
);
CREATE INDEX idx_storage_parent ON storage_locations(parent_location_id);
CREATE INDEX idx_storage_type ON storage_locations(location_type);

CREATE TABLE samples (
    sample_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT NULL,
    parent_sample_id BIGINT NULL,
    sample_code VARCHAR(100) NOT NULL UNIQUE,
    external_sample_id VARCHAR(100) NULL,
    -- The study subject (participant) the Sample came from; a plain identifier, not a registry.
    subject_code VARCHAR(100) NULL,
    -- Which tube this is among those received for the same subject, sample type and collection.
    aliquot_number INTEGER NULL,
    sample_type_id BIGINT NULL,
    label VARCHAR(255) NULL,
    subtype VARCHAR(100) NULL,
    source_type VARCHAR(100) NULL,
    source_description VARCHAR(255) NULL,
    collection_date TIMESTAMP NULL,
    received_date TIMESTAMP NULL,
    status VARCHAR(50) NOT NULL DEFAULT 'expected',
    current_quantity NUMERIC(16,6) NULL,
    quantity_unit VARCHAR(50) NULL,
    concentration NUMERIC(16,6) NULL,
    concentration_unit VARCHAR(50) NULL,
    storage_location_id BIGINT NULL,
    is_consumed BOOLEAN NOT NULL DEFAULT FALSE,
    is_disposed BOOLEAN NOT NULL DEFAULT FALSE,
    expiration_date TIMESTAMP NULL,
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_sample_batch FOREIGN KEY (batch_id) REFERENCES batches(batch_id) ON DELETE SET NULL,
    CONSTRAINT fk_sample_parent FOREIGN KEY (parent_sample_id) REFERENCES samples(sample_id) ON DELETE SET NULL,
    CONSTRAINT fk_sample_type FOREIGN KEY (sample_type_id) REFERENCES sample_types(sample_type_id) ON DELETE RESTRICT,
    CONSTRAINT fk_sample_storage FOREIGN KEY (storage_location_id) REFERENCES storage_locations(storage_location_id) ON DELETE SET NULL,
    -- Shipping batches contain only root/original samples.
    CONSTRAINT ck_sample_batch_root CHECK (parent_sample_id IS NULL OR batch_id IS NULL),
    CONSTRAINT ck_sample_not_own_parent CHECK (parent_sample_id IS NULL OR parent_sample_id <> sample_id),
    CONSTRAINT ck_sample_aliquot_number CHECK (aliquot_number IS NULL OR aliquot_number > 0)
);
CREATE INDEX idx_sample_batch ON samples(batch_id);
CREATE INDEX idx_sample_parent ON samples(parent_sample_id);
CREATE INDEX idx_sample_external_id ON samples(external_sample_id);
CREATE INDEX idx_sample_status ON samples(status);
CREATE INDEX idx_sample_received_date ON samples(received_date);
CREATE INDEX idx_sample_type ON samples(sample_type_id);
CREATE INDEX idx_sample_storage ON samples(storage_location_id);
CREATE INDEX idx_sample_subject ON samples(subject_code);

-- Permanent provenance for rows of the retired materials table. Each legacy
-- Material resolved to exactly one Sample; its code stays searchable and the
-- full original row is kept as JSON.
CREATE TABLE legacy_material_records (
    legacy_material_id BIGINT PRIMARY KEY,
    sample_id BIGINT NOT NULL,
    material_code VARCHAR(120) NOT NULL UNIQUE,
    resolution VARCHAR(20) NOT NULL,
    record JSONB NOT NULL,
    migrated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_legacy_material_sample FOREIGN KEY (sample_id) REFERENCES samples(sample_id) ON DELETE RESTRICT,
    CONSTRAINT ck_legacy_material_resolution CHECK (resolution IN ('matched', 'new_sample'))
);
CREATE INDEX idx_legacy_material_sample ON legacy_material_records(sample_id);

CREATE TABLE process_events (
    process_event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    process_code VARCHAR(100) NOT NULL UNIQUE,
    process_type_id BIGINT NOT NULL,
    protocol_id BIGINT NULL,
    batch_code VARCHAR(100) NULL,
    operator_name VARCHAR(150) NULL,
    started_at TIMESTAMP NULL,
    completed_at TIMESTAMP NULL,
    status VARCHAR(50) NOT NULL DEFAULT 'planned',
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_process_type FOREIGN KEY (process_type_id) REFERENCES process_types(process_type_id) ON DELETE RESTRICT,
    CONSTRAINT fk_process_protocol FOREIGN KEY (protocol_id) REFERENCES protocols(protocol_id) ON DELETE SET NULL
);
CREATE INDEX idx_process_type ON process_events(process_type_id);
CREATE INDEX idx_process_protocol ON process_events(protocol_id);
CREATE INDEX idx_process_batch ON process_events(batch_code);
CREATE INDEX idx_process_status ON process_events(status);
CREATE INDEX idx_process_completed ON process_events(completed_at);

CREATE TABLE process_event_inputs (
    process_event_id BIGINT NOT NULL,
    sample_id BIGINT NOT NULL,
    quantity_used NUMERIC(16,6) NULL,
    quantity_unit VARCHAR(50) NULL,
    notes TEXT NULL,
    PRIMARY KEY (process_event_id, sample_id),
    CONSTRAINT fk_process_input_event FOREIGN KEY (process_event_id) REFERENCES process_events(process_event_id) ON DELETE CASCADE,
    CONSTRAINT fk_process_input_sample FOREIGN KEY (sample_id) REFERENCES samples(sample_id) ON DELETE RESTRICT
);
CREATE INDEX idx_process_input_sample ON process_event_inputs(sample_id);

CREATE TABLE process_event_outputs (
    process_event_id BIGINT NOT NULL,
    sample_id BIGINT NOT NULL,
    quantity_generated NUMERIC(16,6) NULL,
    quantity_unit VARCHAR(50) NULL,
    notes TEXT NULL,
    PRIMARY KEY (process_event_id, sample_id),
    CONSTRAINT fk_process_output_event FOREIGN KEY (process_event_id) REFERENCES process_events(process_event_id) ON DELETE CASCADE,
    CONSTRAINT fk_process_output_sample FOREIGN KEY (sample_id) REFERENCES samples(sample_id) ON DELETE RESTRICT
);
CREATE INDEX idx_process_output_sample ON process_event_outputs(sample_id);

CREATE TABLE sample_quantity_events (
    quantity_event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sample_id BIGINT NOT NULL,
    event_type VARCHAR(50) NOT NULL,
    quantity_change NUMERIC(16,6) NOT NULL,
    quantity_unit VARCHAR(50) NOT NULL,
    quantity_before NUMERIC(16,6),
    quantity_after NUMERIC(16,6),
    related_process_event_id BIGINT NULL,
    -- The assay that used this volume, when an assay recorded it. Its foreign key follows the assays table.
    related_assay_id BIGINT NULL,
    event_date TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    operator_name VARCHAR(150),
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_quantity_sample FOREIGN KEY (sample_id) REFERENCES samples(sample_id) ON DELETE RESTRICT,
    CONSTRAINT fk_quantity_process FOREIGN KEY (related_process_event_id) REFERENCES process_events(process_event_id) ON DELETE SET NULL
);
CREATE INDEX idx_quantity_sample ON sample_quantity_events(sample_id);
CREATE INDEX idx_quantity_process ON sample_quantity_events(related_process_event_id);

-- A reusable assay procedure. Each row of assays is one execution of it on one Sample.
CREATE TABLE assay_definitions (
    assay_definition_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assay_code VARCHAR(100) NOT NULL UNIQUE,
    assay_name VARCHAR(255) NOT NULL,
    assay_type VARCHAR(100) NOT NULL,
    target VARCHAR(255),
    protocol_id BIGINT NULL,
    description TEXT,
    kit VARCHAR(255) NULL,
    instrument VARCHAR(255) NULL,
    -- Sample volume one execution typically uses; each execution records its own.
    typical_volume NUMERIC(16,6) NULL,
    typical_volume_unit VARCHAR(50) NULL,
    -- Provenance when the definition was imported from a workbook.
    source_file_name VARCHAR(255) NULL,
    source_sha256 CHAR(64) NULL,
    imported_at TIMESTAMPTZ NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_assay_definition_protocol FOREIGN KEY (protocol_id) REFERENCES protocols(protocol_id) ON DELETE SET NULL
);
CREATE INDEX idx_assay_definition_type ON assay_definitions(assay_type);
CREATE INDEX idx_assay_definition_target ON assay_definitions(target);

-- The results an execution of the assay reports, e.g. "CT" for analyte "LACV".
CREATE TABLE assay_definition_results (
    assay_definition_result_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assay_definition_id BIGINT NOT NULL,
    analyte VARCHAR(255) NULL,
    result_name VARCHAR(255) NOT NULL,
    unit VARCHAR(50) NULL,
    value_type VARCHAR(20) NOT NULL DEFAULT 'either',
    sort_order INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT fk_definition_result_definition FOREIGN KEY (assay_definition_id) REFERENCES assay_definitions(assay_definition_id) ON DELETE CASCADE,
    CONSTRAINT ck_definition_result_value_type CHECK (value_type IN ('numeric', 'text', 'either'))
);
CREATE INDEX idx_definition_result_definition ON assay_definition_results(assay_definition_id);

CREATE TABLE assay_runs (
    assay_run_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_code VARCHAR(100) NOT NULL UNIQUE,
    run_type VARCHAR(100),
    instrument VARCHAR(150),
    platform VARCHAR(150),
    operator_name VARCHAR(150),
    started_at TIMESTAMP,
    completed_at TIMESTAMP,
    status VARCHAR(50) NOT NULL DEFAULT 'planned',
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_assay_run_type ON assay_runs(run_type);
CREATE INDEX idx_assay_run_status ON assay_runs(status);

-- One execution of an assay definition on one Sample.
CREATE TABLE assays (
    assay_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assay_instance_code VARCHAR(100) NOT NULL UNIQUE,
    sample_id BIGINT NOT NULL,
    assay_definition_id BIGINT NOT NULL,
    assay_run_id BIGINT NULL,
    operator_name VARCHAR(150) NULL,
    assay_date TIMESTAMP NULL,
    status VARCHAR(50) NOT NULL DEFAULT 'planned',
    qc_status VARCHAR(50) NOT NULL DEFAULT 'not_reviewed',
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_assay_sample FOREIGN KEY (sample_id) REFERENCES samples(sample_id) ON DELETE RESTRICT,
    CONSTRAINT fk_assay_definition FOREIGN KEY (assay_definition_id) REFERENCES assay_definitions(assay_definition_id) ON DELETE RESTRICT,
    CONSTRAINT fk_assay_run FOREIGN KEY (assay_run_id) REFERENCES assay_runs(assay_run_id) ON DELETE SET NULL
);
CREATE INDEX idx_assay_sample ON assays(sample_id);
CREATE INDEX idx_assay_definition ON assays(assay_definition_id);
CREATE INDEX idx_assay_run ON assays(assay_run_id);
CREATE INDEX idx_assay_status ON assays(status);

ALTER TABLE sample_quantity_events ADD CONSTRAINT fk_quantity_assay FOREIGN KEY (related_assay_id) REFERENCES assays(assay_id) ON DELETE RESTRICT;
CREATE INDEX idx_quantity_assay ON sample_quantity_events(related_assay_id);
CREATE INDEX idx_assay_date ON assays(assay_date);

-- Derived samples produced by an assay (for example a library prepared during sequencing).
CREATE TABLE assay_outputs (
    assay_id BIGINT NOT NULL,
    sample_id BIGINT NOT NULL,
    notes TEXT NULL,
    PRIMARY KEY (assay_id, sample_id),
    CONSTRAINT fk_assay_output_assay FOREIGN KEY (assay_id) REFERENCES assays(assay_id) ON DELETE CASCADE,
    CONSTRAINT fk_assay_output_sample FOREIGN KEY (sample_id) REFERENCES samples(sample_id) ON DELETE RESTRICT
);
CREATE INDEX idx_assay_output_sample ON assay_outputs(sample_id);

CREATE TABLE assay_results (
    assay_result_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assay_id BIGINT NOT NULL,
    analyte VARCHAR(255) NULL,
    result_name VARCHAR(255) NOT NULL,
    numeric_value NUMERIC(20,8) NULL,
    text_value TEXT NULL,
    unit VARCHAR(50) NULL,
    interpretation VARCHAR(255) NULL,
    qc_status VARCHAR(50) NOT NULL DEFAULT 'not_reviewed',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_assay_result_assay FOREIGN KEY (assay_id) REFERENCES assays(assay_id) ON DELETE CASCADE
);
CREATE INDEX idx_result_assay ON assay_results(assay_id);
CREATE INDEX idx_result_analyte ON assay_results(analyte);
CREATE INDEX idx_result_name ON assay_results(result_name);

CREATE TABLE storage_events (
    storage_event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sample_id BIGINT NOT NULL,
    from_location_id BIGINT NULL,
    to_location_id BIGINT NULL,
    event_type VARCHAR(50) NOT NULL,
    event_date TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    operator_name VARCHAR(150) NULL,
    notes TEXT,
    CONSTRAINT fk_storage_event_sample FOREIGN KEY (sample_id) REFERENCES samples(sample_id) ON DELETE RESTRICT,
    CONSTRAINT fk_storage_event_from FOREIGN KEY (from_location_id) REFERENCES storage_locations(storage_location_id) ON DELETE SET NULL,
    CONSTRAINT fk_storage_event_to FOREIGN KEY (to_location_id) REFERENCES storage_locations(storage_location_id) ON DELETE SET NULL
);
CREATE INDEX idx_storage_event_sample ON storage_events(sample_id);
CREATE INDEX idx_storage_event_date ON storage_events(event_date);

CREATE TABLE data_files (
    data_file_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assay_id BIGINT NULL,
    sample_id BIGINT NULL,
    file_type VARCHAR(50) NOT NULL,
    file_name VARCHAR(255) NOT NULL,
    file_location VARCHAR(1000) NOT NULL,
    checksum_sha256 CHAR(64) NULL,
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_data_file_assay FOREIGN KEY (assay_id) REFERENCES assays(assay_id) ON DELETE SET NULL,
    CONSTRAINT fk_data_file_sample FOREIGN KEY (sample_id) REFERENCES samples(sample_id) ON DELETE SET NULL
);
CREATE INDEX idx_data_file_assay ON data_files(assay_id);
CREATE INDEX idx_data_file_sample ON data_files(sample_id);
CREATE INDEX idx_data_file_type ON data_files(file_type);

