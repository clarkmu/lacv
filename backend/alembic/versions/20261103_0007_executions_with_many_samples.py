def _move_results(bind) -> None:
    specification = {
        row["assay_definition_id"]: row
        for row in bind.execute(sa.text("SELECT assay_definition_id, result_name, result_unit FROM assay_definitions")).mappings().all()
    }
    executions = bind.execute(sa.text("SELECT assay_execution_id, assay_definition_id, sample_id FROM assay_executions ORDER BY assay_execution_id")).mappings().all()
    results: dict[int, list] = {}
    for row in bind.execute(sa.text("""
        SELECT assay_id, analyte, result_name, numeric_value, text_value, unit, interpretation, qc_status
        FROM assay_results ORDER BY assay_id, assay_result_id
    """)).mappings().all():
        results.setdefault(row["assay_id"], []).append(row)

    for execution in executions:
        rows = results.get(execution["assay_execution_id"], [])
        if not rows:
            continue
        spec = specification[execution["assay_definition_id"]]
        kept = rows[0] if len(rows) == 1 else next((row for row in rows if _matches(row, spec["result_name"])), None)
        if kept is not None:
            numeric, text = kept["numeric_value"], None if kept["numeric_value"] is not None else kept["text_value"]
            bind.execute(
                sa.text("UPDATE assay_execution_samples SET result_numeric = :numeric, result_text = :text WHERE assay_execution_id = :execution AND sample_id = :sample"),
                {"numeric": numeric, "text": text, "execution": execution["assay_execution_id"], "sample": execution["sample_id"]},
            )
        if _loses_information(rows, kept, spec):
            listing = "\n".join(f"- {_describe(row)}" for row in rows)
            bind.execute(
                sa.text("UPDATE assay_executions SET notes = concat_ws(E'\\n\\n', notes, CAST(:text AS TEXT)) WHERE assay_execution_id = :execution"),
                {"text": f"{NOTES_HEADING}\n{listing}", "execution": execution["assay_execution_id"]},
            )


def _label(analyte: str | None, result_name: str) -> str:
    return f"{analyte} {result_name}" if analyte else result_name


def _matches(row, result_name: str | None) -> bool:
    return result_name is not None and _label(row["analyte"], row["result_name"]).lower() == result_name.lower()


def _loses_information(rows: list, kept, spec) -> bool:
    if kept is None or len(rows) > 1:
        return True
    return bool(
        kept["interpretation"]
        or kept["qc_status"] not in (None, "not_reviewed")
        or (kept["numeric_value"] is not None and kept["text_value"])
        or (spec["result_name"] and not _matches(kept, spec["result_name"]))
        or (kept["unit"] or None) != (spec["result_unit"] or None)
    )


def _describe(row) -> str:
    value = row["numeric_value"] if row["numeric_value"] is not None else row["text_value"]
    if isinstance(value, Decimal):
        value = format(value.normalize(), "f")
    parts = [f"{_label(row['analyte'], row['result_name'])}: {value if value is not None else '(no value)'}"]
    if row["numeric_value"] is not None and row["text_value"]:
        parts.append(f"text {row['text_value']}")
    if row["unit"]:
        parts[0] += f" {row['unit']}"
    extras = [item for item in (row["interpretation"], f"QC {row['qc_status']}" if row["qc_status"] else None) if item]
    return parts[0] + (f" ({'; '.join(extras)})" if extras else "") + ("" if len(parts) == 1 else f"; {parts[1]}")
