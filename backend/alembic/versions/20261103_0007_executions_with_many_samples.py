def _single_result_specification(bind) -> None:
    op.execute("""
        ALTER TABLE assay_definitions
            ADD COLUMN result_name VARCHAR(255) NULL,
            ADD COLUMN result_unit VARCHAR(50) NULL,
            ADD COLUMN result_value_type VARCHAR(20) NOT NULL DEFAULT 'either',
            ADD CONSTRAINT ck_definition_result_value_type CHECK (result_value_type IN ('numeric', 'text', 'either'))
    """)
    rows = bind.execute(sa.text("""
        SELECT assay_definition_id, analyte, result_name, unit, value_type
        FROM assay_definition_results
        ORDER BY assay_definition_id, sort_order, assay_definition_result_id
    """)).mappings().all()
    by_definition: dict[int, list] = {}
    for row in rows:
        by_definition.setdefault(row["assay_definition_id"], []).append(row)
    for definition_id, expected in by_definition.items():
        first, others = expected[0], expected[1:]
        bind.execute(
            sa.text("UPDATE assay_definitions SET result_name = :name, result_unit = :unit, result_value_type = :value_type WHERE assay_definition_id = :id"),
            {"name": _label(first["analyte"], first["result_name"]), "unit": first["unit"], "value_type": first["value_type"], "id": definition_id},
        )
        if others:
            listed = "; ".join(_label(row["analyte"], row["result_name"]) + (f" ({row['unit']})" if row["unit"] else "") for row in others)
            bind.execute(
                sa.text("UPDATE assay_definitions SET description = concat_ws(E'\\n\\n', description, CAST(:text AS TEXT)) WHERE assay_definition_id = :id"),
                {"text": f"Also reported before executions held one result per sample: {listed}.", "id": definition_id},
            )
    op.execute("DROP TABLE assay_definition_results")


