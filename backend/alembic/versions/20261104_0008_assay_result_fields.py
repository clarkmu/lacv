def _restore_fields(bind) -> dict[int, dict[str, tuple[int, str | None]]]:
    """Each assay's fields by label (lower case) -> (field id, unit)."""
    fields: dict[int, dict[str, tuple[int, str | None]]] = {}
    with_values = {row[0] for row in bind.execute(sa.text("""
        SELECT DISTINCT e.assay_definition_id FROM assay_execution_samples x JOIN assay_executions e USING (assay_execution_id)
        WHERE x.result_numeric IS NOT NULL OR x.result_text IS NOT NULL
    """)).all()}
    for definition in bind.execute(sa.text(
        "SELECT assay_definition_id, result_name, result_unit, result_value_type, description FROM assay_definitions ORDER BY assay_definition_id"
    )).mappings().all():
        definition_id = definition["assay_definition_id"]
        fields[definition_id] = {}
        first = definition["result_name"] or ("Result" if definition_id in with_values else None)
        if first:
            fields[definition_id][first.lower()] = (_add_field(bind, definition_id, first, definition["result_unit"], definition["result_value_type"], 0), definition["result_unit"])
        match = DESCRIPTION_LINE.search(definition["description"] or "")
        if match:
            for order, item in enumerate(match.group("fields").split("; "), start=1):
                label, unit = _label_and_unit(item)
                if label.lower() not in fields[definition_id]:
                    fields[definition_id][label.lower()] = (_add_field(bind, definition_id, label, unit, "either", order), unit)
            description = definition["description"][: match.start()] or None
            bind.execute(sa.text("UPDATE assay_definitions SET description = :description WHERE assay_definition_id = :id"), {"description": description, "id": definition_id})
    return fields


def _add_field(bind, definition_id: int, label: str, unit: str | None, value_type: str, order: int) -> int:
    return bind.execute(
        sa.text("""
            INSERT INTO assay_definition_results (assay_definition_id, result_name, unit, value_type, sort_order)
            VALUES (:definition, :name, :unit, :value_type, :order) RETURNING assay_definition_result_id
        """),
        {"definition": definition_id, "name": label, "unit": unit, "value_type": value_type, "order": order},
    ).scalar_one()


def _move_values(bind, fields: dict[int, dict[str, tuple[int, str | None]]]) -> None:
    for row in bind.execute(sa.text("""
        SELECT x.assay_execution_sample_id, e.assay_definition_id, x.result_numeric, x.result_text
        FROM assay_execution_samples x JOIN assay_executions e USING (assay_execution_id)
        WHERE x.result_numeric IS NOT NULL OR x.result_text IS NOT NULL
        ORDER BY x.assay_execution_sample_id
    """)).mappings().all():
        field_id, _ = next(iter(fields[row["assay_definition_id"]].values()))
        _upsert(bind, row["assay_execution_sample_id"], field_id, row["result_numeric"], row["result_text"], None, None)


def _read_back_notes(bind, fields: dict[int, dict[str, tuple[int, str | None]]]) -> None:
    """Results 0007 wrote into notes: one execution, one Sample, one line per original result."""
    for execution in bind.execute(sa.text(f"""
        SELECT e.assay_execution_id, e.assay_definition_id, e.notes, min(x.assay_execution_sample_id) AS sample_row, count(x.*) AS samples
        FROM assay_executions e JOIN assay_execution_samples x USING (assay_execution_id)
        WHERE e.notes LIKE :heading
        GROUP BY e.assay_execution_id, e.assay_definition_id, e.notes
        ORDER BY e.assay_execution_id
    """), {"heading": f"%{NOTES_HEADING}%"}).mappings().all():
        if execution["samples"] != 1:
            continue
        before, _, block = execution["notes"].partition(NOTES_HEADING)
        lines = block.strip("\n").split("\n")
        known = fields[execution["assay_definition_id"]]
        parsed = [_parse_line(line, known) for line in lines]
        if not lines or any(item is None for item in parsed):
            continue
        for field_id, numeric, text, interpretation, qc in parsed:
            _upsert(bind, execution["sample_row"], field_id, numeric, text, interpretation, qc)
        bind.execute(
            sa.text("UPDATE assay_executions SET notes = :notes WHERE assay_execution_id = :id"),
            {"notes": before.rstrip("\n") or None, "id": execution["assay_execution_id"]},
        )


def _parse_line(line: str, known: dict[str, tuple[int, str | None]]):
    """'- LACV CT: 31.2 cycles (positive; QC accepted)', as 0007 wrote it, back into its parts.

    None when the line does not read back without losing something (for example a text value written alongside a number).
    """
    if not line.startswith("- "):
        return None
    head = line[2:]
    if "; text " in head and head.rfind("; text ") > head.rfind(")"):
        return None
    extras: list[str] = []
    if head.endswith(")") and " (" in head:
        head, inner = head.rsplit(" (", 1)
        extras = inner[:-1].split("; ")
    label = next((name for name in sorted(known, key=len, reverse=True) if head.lower().startswith(f"{name}: ")), None)
    if label is None:
        return None
    field_id, unit = known[label]
    value = head[len(label) + 2:]
    if unit and value.endswith(f" {unit}"):
        value = value[: -len(unit) - 1]
    interpretation = next((item for item in extras if not item.startswith("QC ")), None)
    qc = next((item[3:] for item in extras if item.startswith("QC ")), None)
    numeric = text = None
    if value != "(no value)":
        if NUMBER.match(value):
            try:
                numeric = Decimal(value)
            except InvalidOperation:
                text = value
        else:
            text = value
    if numeric is None and text is None and interpretation is None:
        return None
    return field_id, numeric, text, interpretation, qc


def _label_and_unit(item: str) -> tuple[str, str | None]:
    match = re.match(r"^(?P<label>.*?) \((?P<unit>[^()]*)\)$", item)
    return (match.group("label"), match.group("unit")) if match else (item, None)


def _upsert(bind, sample_row: int, field_id: int, numeric, text, interpretation, qc) -> None:
    if numeric is None and text is None and interpretation is None:
        return
    bind.execute(sa.text("""
        INSERT INTO assay_execution_results (assay_execution_sample_id, assay_definition_result_id, numeric_value, text_value, interpretation, qc_status)
        VALUES (:sample_row, :field, :numeric, :text, :interpretation, COALESCE(:qc, 'not_reviewed'))
        ON CONFLICT (assay_execution_sample_id, assay_definition_result_id) DO UPDATE SET
            numeric_value = EXCLUDED.numeric_value, text_value = EXCLUDED.text_value,
            interpretation = EXCLUDED.interpretation, qc_status = EXCLUDED.qc_status
    """), {"sample_row": sample_row, "field": field_id, "numeric": numeric, "text": text, "interpretation": interpretation, "qc": qc})
